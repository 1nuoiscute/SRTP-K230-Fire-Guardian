#include "ssd1306.h"

#include <string.h>

static int send_commands(Ssd1306 *screen, const uint8_t *commands, size_t n)
{
    uint8_t packet[32];
    if (n + 1 > sizeof(packet)) return -1;
    packet[0] = 0x00; /* SSD1306 command stream */
    memcpy(packet + 1, commands, n);
    return gpio_i2c_write(screen->bus, screen->address, packet, n + 1);
}

int ssd1306_init(Ssd1306 *screen, GpioI2c *bus)
{
    static const uint8_t init[] = {
        0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40,
        0x8D, 0x14, 0x20, 0x02, 0xA1, 0xC8, 0xDA, 0x12,
        0x81, 0xCF, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0xAF
    };
    memset(screen, 0, sizeof(*screen));
    screen->bus = bus;
    if (gpio_i2c_write(bus, 0x3C, NULL, 0) == 0) screen->address = 0x3C;
    else if (gpio_i2c_write(bus, 0x3D, NULL, 0) == 0) screen->address = 0x3D;
    else return -1;
    if (send_commands(screen, init, sizeof(init))) return -1;
    memset(screen->displayed, 0xFF, sizeof(screen->displayed));
    return 0;
}

void ssd1306_clear(Ssd1306 *screen)
{
    memset(screen->pixels, 0, sizeof(screen->pixels));
}

static const uint8_t *glyph(char ch)
{
    static const uint8_t digits[10][5] = {
        {0x3E,0x51,0x49,0x45,0x3E}, {0x00,0x42,0x7F,0x40,0x00},
        {0x42,0x61,0x51,0x49,0x46}, {0x21,0x41,0x45,0x4B,0x31},
        {0x18,0x14,0x12,0x7F,0x10}, {0x27,0x45,0x45,0x45,0x39},
        {0x3C,0x4A,0x49,0x49,0x30}, {0x01,0x71,0x09,0x05,0x03},
        {0x36,0x49,0x49,0x49,0x36}, {0x06,0x49,0x49,0x29,0x1E}
    };
    static const uint8_t letters[26][5] = {
        {0x7E,0x11,0x11,0x11,0x7E}, {0x7F,0x49,0x49,0x49,0x36},
        {0x3E,0x41,0x41,0x41,0x22}, {0x7F,0x41,0x41,0x22,0x1C},
        {0x7F,0x49,0x49,0x49,0x41}, {0x7F,0x09,0x09,0x09,0x01},
        {0x3E,0x41,0x49,0x49,0x7A}, {0x7F,0x08,0x08,0x08,0x7F},
        {0x00,0x41,0x7F,0x41,0x00}, {0x20,0x40,0x41,0x3F,0x01},
        {0x7F,0x08,0x14,0x22,0x41}, {0x7F,0x40,0x40,0x40,0x40},
        {0x7F,0x02,0x0C,0x02,0x7F}, {0x7F,0x04,0x08,0x10,0x7F},
        {0x3E,0x41,0x41,0x41,0x3E}, {0x7F,0x09,0x09,0x09,0x06},
        {0x3E,0x41,0x51,0x21,0x5E}, {0x7F,0x09,0x19,0x29,0x46},
        {0x46,0x49,0x49,0x49,0x31}, {0x01,0x01,0x7F,0x01,0x01},
        {0x3F,0x40,0x40,0x40,0x3F}, {0x1F,0x20,0x40,0x20,0x1F},
        {0x7F,0x20,0x18,0x20,0x7F}, {0x63,0x14,0x08,0x14,0x63},
        {0x03,0x04,0x78,0x04,0x03}, {0x61,0x51,0x49,0x45,0x43}
    };
    static const uint8_t space[5] = {0,0,0,0,0};
    static const uint8_t dot[5] = {0,0x60,0x60,0,0};
    static const uint8_t colon[5] = {0,0x36,0x36,0,0};
    static const uint8_t percent[5] = {0x63,0x13,0x08,0x64,0x63};
    static const uint8_t minus[5] = {0x08,0x08,0x08,0x08,0x08};
    if (ch >= '0' && ch <= '9') return digits[ch - '0'];
    if (ch >= 'A' && ch <= 'Z') return letters[ch - 'A'];
    if (ch == '.') return dot;
    if (ch == ':') return colon;
    if (ch == '%') return percent;
    if (ch == '-') return minus;
    return space;
}

void ssd1306_text(Ssd1306 *screen, int x, int y, const char *text)
{
    for (; *text; ++text, x += 6) {
        const uint8_t *columns = glyph(*text);
        for (int column = 0; column < 5; ++column) {
            int px = x + column;
            if (px < 0 || px >= OLED_WIDTH) continue;
            for (int bit = 0; bit < 7; ++bit) {
                int py = y + bit;
                if ((columns[column] & (1U << bit)) &&
                    py >= 0 && py < OLED_HEIGHT)
                    screen->pixels[(py / 8) * OLED_WIDTH + px] |=
                        (uint8_t)(1U << (py % 8));
            }
        }
    }
}

int ssd1306_refresh(Ssd1306 *screen)
{
    uint8_t data[OLED_WIDTH + 1];
    data[0] = 0x40; /* SSD1306 data stream */
    for (int page = 0; page < 8; ++page) {
        uint8_t *current = screen->pixels + page * OLED_WIDTH;
        uint8_t *previous = screen->displayed + page * OLED_WIDTH;
        if (memcmp(current, previous, OLED_WIDTH) == 0) continue;
        uint8_t position[3] = {(uint8_t)(0xB0 | page), 0x00, 0x10};
        if (send_commands(screen, position, sizeof(position))) return -1;
        memcpy(data + 1, current, OLED_WIDTH);
        if (gpio_i2c_write(screen->bus, screen->address,
                           data, sizeof(data))) return -1;
        memcpy(previous, current, OLED_WIDTH);
    }
    return 0;
}
